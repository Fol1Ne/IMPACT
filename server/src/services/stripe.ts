import Stripe from 'stripe';
import { z } from 'zod';
import type { CheckoutStatus, PaymentState, ProductInfo } from '../../../shared/types';
import { getConfig } from '../config';
import { HttpError } from '../errors';
import { log } from '../logger';
import type { EntitlementStore } from './entitlements';

export const PRODUCT_INCLUDES = [
  'A structured earthquake preparedness plan: before, during and after shaking',
  'Context for the event you select: magnitude class and depth class from USGS data',
  'A printable checklist with links to official guidance',
];

export function getProduct(): ProductInfo {
  const p = getConfig().product;
  return {
    id: p.id, name: p.name, priceCents: p.priceCents, currency: p.currency, includes: PRODUCT_INCLUDES,
    description: 'A one-time digital preparedness package generated by IMPACT. Sandbox purchase only: it is not a donation and sends no money to any charity.',
  };
}

/** Returns a human-readable problem, or null when the secret key looks usable and is test-mode. */
export function stripeProblem(): string | null {
  const key = getConfig().stripe.secretKey;
  if (!key) return 'STRIPE_SECRET_KEY is not set.';
  if (!/^(sk|rk)_test_/.test(key)) return 'STRIPE_SECRET_KEY must be a test-mode key (starting sk_test_ or rk_test_). Live keys are refused.';
  return null;
}

export const getStripe = (): Stripe | null => (stripeProblem() ? null : new Stripe(getConfig().stripe.secretKey));

export const CreateSessionSchema = z.object({
  product: z.literal('enhanced-preparedness'),
  eventId: z.string().regex(/^[a-z0-9]{4,40}$/i).optional(),
}).strict();

export const SessionIdSchema = z.string().regex(/^cs_test_[A-Za-z0-9]{10,200}$/);

export async function createCheckoutSession(stripe: Stripe, input: z.infer<typeof CreateSessionSchema>): Promise<{ url: string; id: string }> {
  const cfg = getConfig();
  const product = getProduct(); // price always comes from the server, never from the browser
  const session = await stripe.checkout.sessions.create({
    mode: 'payment',
    line_items: [{
      quantity: 1,
      price_data: { currency: product.currency, unit_amount: product.priceCents, product_data: { name: `${product.name} (sandbox)`, description: product.description } },
    }],
    success_url: `${cfg.clientUrl}/checkout/success?session_id={CHECKOUT_SESSION_ID}`,
    cancel_url: `${cfg.clientUrl}/checkout/cancel`,
    metadata: { product: product.id, ...(input.eventId ? { eventId: input.eventId } : {}) },
  });
  if (!session.url) throw new HttpError(502, 'checkout_failed', 'Stripe did not return a checkout URL.');
  return { url: session.url, id: session.id };
}

type SessionLike = Pick<Stripe.Checkout.Session, 'id' | 'status' | 'payment_status' | 'metadata' | 'amount_total' | 'currency' | 'livemode'>;

/** Only Stripe's own `payment_status === "paid"` counts as paid. */
export function mapSessionState(s: Pick<SessionLike, 'status' | 'payment_status'>): PaymentState {
  if (s.payment_status === 'paid') return 'paid';
  if (s.status === 'expired') return 'expired';
  if (s.status === 'complete') return 'unpaid'; // completed but funds not confirmed (e.g. async method)
  return 'pending';
}

/** Grants the benefit only for a paid, test-mode session created for our product. */
function applyPaidSession(s: SessionLike, store: EntitlementStore): boolean {
  if (mapSessionState(s) !== 'paid') return false;
  if (s.livemode) return false;
  if (s.metadata?.product !== getConfig().product.id) return false;
  store.grant(s.id);
  return true;
}

export async function verifySession(stripe: Stripe, store: EntitlementStore, sessionId: string): Promise<CheckoutStatus> {
  let s: SessionLike;
  try {
    s = await stripe.checkout.sessions.retrieve(sessionId);
  } catch (err) {
    log('warn', 'stripe_retrieve_failed', { reason: (err as Error).name });
    throw new HttpError(502, 'verification_unavailable', 'Could not verify the payment with Stripe right now. Try again.');
  }
  applyPaidSession(s, store);
  return { state: mapSessionState(s), entitled: store.has(s.id), amount: s.amount_total ?? null, currency: s.currency ?? null, livemode: false };
}

export function handleWebhookEvent(event: Stripe.Event, store: EntitlementStore): { handled: boolean; granted: boolean } {
  if (event.type === 'checkout.session.completed' || event.type === 'checkout.session.async_payment_succeeded') {
    const granted = applyPaidSession(event.data.object as Stripe.Checkout.Session, store);
    return { handled: true, granted };
  }
  return { handled: false, granted: false };
}
